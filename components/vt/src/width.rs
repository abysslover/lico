/// 0 (zero width: a control, a combining mark, a joiner, a variation selector), 1 or 2 (East Asian wide and fullwidth, Hangul, most emoji).
pub fn char_width(c: char) -> u8 {
    let u = c as u32;
    if u < 0x20 || (0x7F..0xA0).contains(&u) {
        return 0;
    }
    if u < 0x300 {
        return 1;
    }
    if within(u, ZERO) {
        0
    } else if within(u, WIDE) {
        2
    } else {
        1
    }
}
