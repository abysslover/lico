//! The width of a character in cells: 0, 1 or 2. The common ranges of East Asian Wide and Fullwidth, and of the characters that take no cell; a character not listed is 1.

fn within(c: u32, table: &[(u32, u32)]) -> bool {
    table.binary_search_by(|&(lo, hi)| if c < lo { std::cmp::Ordering::Greater } else if c > hi { std::cmp::Ordering::Less } else { std::cmp::Ordering::Equal }).is_ok()
}

