"""Generates the table of the opening brackets and quotation marks that are not ASCII (M02-P03, F1 of the gate verifier).

The header the host writes in front of a text from another session begins with `[`. A line of that text that begins with a glyph a reader takes for `[`
(a fullwidth bracket, a corner bracket) and goes on with letters that look like `from` (a Cyrillic o, fullwidth letters) cannot be told from it by the
letters. So the host puts one space in front of every line that begins with an ASCII `[` or with one of these characters, whatever follows. The table is the
Unicode general categories Ps (open punctuation) and Pi (initial quote) without the ASCII ones, of ONE version of Unicode, and not of the one the compiler or
the system happens to have:

    python -m lico_protocol.gen_unicode_openers            write the Python mirror and the Rust table
    python -m lico_protocol.gen_unicode_openers --check    exit 1 when either file is not what this Python's unicodedata gives

Python 3.12 ships Unicode 15.0.0. With another Python the generator refuses; to move to another version, change UNICODE on purpose and say so in the commit.
"""
from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

from lico_protocol.gen_unicode_marks import UNICODE, body

CATEGORIES = ("Ps", "Pi")
REPO = Path(__file__).resolve().parents[2]
PYTHON_FILE = REPO / "src" / "lico_protocol" / "unicode_openers.py"
RUST_FILE = REPO / "src" / "host" / "hostd" / "src" / "marks" / "openers.rs"


def ranges() -> list[tuple[int, int]]:
    """Sorted, with neighbours joined: the non-ASCII code points of CATEGORIES in the Unicode of this Python."""
    found: list[list[int]] = []
    for code in range(0x80, 0x110000):
        if unicodedata.category(chr(code)) in CATEGORIES:
            if found and found[-1][1] + 1 == code:
                found[-1][1] = code
            else:
                found.append([code, code])
    return [(low, high) for low, high in found]


def python_text(table: list[tuple[int, int]]) -> str:
    return (f'"""GENERATED by lico_protocol/gen_unicode_openers.py: do not edit. The opening brackets (Ps) and the initial quotation marks (Pi) of Unicode {UNICODE}\n'
            f'that are not ASCII, as (first, last) code points, sorted, neighbours joined. The Python mirror of hostd/src/marks/openers.rs."""\n'
            f'UNICODE = "{UNICODE}"\n'
            f"RANGES = (\n{body(table, '    ')}\n)\n")


def rust_text(table: list[tuple[int, int]]) -> str:
    return (f"//! GENERATED by `python -m lico_protocol.gen_unicode_openers`: do not edit. The opening brackets (Ps) and the initial quotation marks (Pi) of\n"
            f"//! Unicode {UNICODE} that are not ASCII, as (first, last) code points, sorted, neighbours joined. The Python mirror is lico_protocol/unicode_openers.py.\n\n"
            f'#[cfg(test)] // read by the unit test only\n'
            f'pub const UNICODE: &str = "{UNICODE}";\n'
            f"pub const RANGES: &[(u32, u32)] = &[\n{body(table, '    ')}\n];\n")


def differing() -> list[str]:
    """The generated files whose text is not what this Python gives."""
    table = ranges()
    wanted = {PYTHON_FILE: python_text(table), RUST_FILE: rust_text(table)}
    return [str(path.relative_to(REPO) if path.is_relative_to(REPO) else path) for path, text in wanted.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text]


def main(argv: list[str]) -> int:
    if unicodedata.unidata_version != UNICODE:
        print(f"this Python has Unicode {unicodedata.unidata_version}, the table is pinned to {UNICODE}: use a Python that has {UNICODE} (3.12), "
              f"or change UNICODE in gen_unicode_marks on purpose", file=sys.stderr)
        return 2
    if argv == ["--check"]:
        wrong = differing()
        print("\n".join(f"{name} differs from what Unicode {UNICODE} gives" for name in wrong) or f"both files are what Unicode {UNICODE} gives")
        return 1 if wrong else 0
    if argv:
        print(__doc__, file=sys.stderr)
        return 2
    table = ranges()
    PYTHON_FILE.write_text(python_text(table), encoding="utf-8")
    RUST_FILE.parent.mkdir(parents=True, exist_ok=True)
    RUST_FILE.write_text(rust_text(table), encoding="utf-8")
    print(f"{len(table)} ranges, {sum(high - low + 1 for low, high in table)} code points of Unicode {UNICODE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
