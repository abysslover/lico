"""Generates the table of characters that draw nothing on their own, or only on the character before them (M02-P03, the V4 gate).

A line of agent text that begins like a record of the host gets `[agent] ` in front. The decision is made on a skeleton of the line, with the characters
that draw nothing removed, so that a lead cannot be hidden behind one. The list of the default-ignorable characters left a gap: the format characters (Cf)
that are not default-ignorable, the nonspacing marks (Mn) and the enclosing marks (Me) draw nothing, or draw on the character before them, and U+2800 (the
blank braille pattern, a symbol) draws an empty cell. This table has all of them, of ONE version of Unicode, and not of the one the compiler or the system
happens to have:

    python -m lico_protocol.gen_unicode_marks            write the Python mirror and the Rust table
    python -m lico_protocol.gen_unicode_marks --check    exit 1 when either file is not what this Python's unicodedata gives

Python 3.12 ships Unicode 15.0.0. With another Python the generator refuses; to move to another version, change UNICODE on purpose and say so in the commit.
"""
from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

UNICODE = "15.0.0"
CATEGORIES = ("Cf", "Mn", "Me")
EXTRA = (0x2800,)                                            # So, but it draws a blank cell: a line can begin with it and look empty
REPO = Path(__file__).resolve().parents[2]
PYTHON_FILE = REPO / "src" / "lico_protocol" / "unicode_marks.py"
RUST_FILE = REPO / "src" / "host" / "hostd" / "src" / "marks" / "table.rs"
PER_LINE = 5


def ranges() -> list[tuple[int, int]]:
    """Sorted, with neighbours joined: the code points of CATEGORIES and EXTRA in the Unicode of this Python."""
    found: list[list[int]] = []
    for code in range(0x110000):
        if unicodedata.category(chr(code)) in CATEGORIES or code in EXTRA:
            if found and found[-1][1] + 1 == code:
                found[-1][1] = code
            else:
                found.append([code, code])
    return [(low, high) for low, high in found]


def body(table: list[tuple[int, int]], indent: str) -> str:
    cells = [f"(0x{low:04x}, 0x{high:04x})," for low, high in table]
    return "\n".join(indent + " ".join(cells[k:k + PER_LINE]) for k in range(0, len(cells), PER_LINE))


def python_text(table: list[tuple[int, int]]) -> str:
    return (f'"""GENERATED by lico_protocol/gen_unicode_marks.py: do not edit. The format characters (Cf), the nonspacing marks (Mn), the enclosing marks (Me)\n'
            f'and U+2800 of Unicode {UNICODE}, as (first, last) code points, sorted, neighbours joined. The Python mirror of hostd/src/marks/table.rs."""\n'
            f'UNICODE = "{UNICODE}"\n'
            f"RANGES = (\n{body(table, '    ')}\n)\n")


def rust_text(table: list[tuple[int, int]]) -> str:
    return (f"//! GENERATED by `python -m lico_protocol.gen_unicode_marks`: do not edit. The format characters (Cf), the nonspacing marks (Mn), the enclosing\n"
            f"//! marks (Me) and U+2800 of Unicode {UNICODE}, as (first, last) code points, sorted, neighbours joined. The Python mirror is lico_protocol/unicode_marks.py.\n\n"
            f'#[cfg(test)] // read by the unit test only\n'
            f'pub const UNICODE: &str = "{UNICODE}";\n'
            f"pub const RANGES: &[(u32, u32)] = &[\n{body(table, '    ')}\n];\n")


def differing() -> list[str]:
    """The generated files whose text is not what this Python gives."""
    table = ranges()
    wanted = {PYTHON_FILE: python_text(table), RUST_FILE: rust_text(table)}
    return [str(path.relative_to(REPO) if path.is_relative_to(REPO) else path) for path, text in wanted.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text]


def main(argv: list[str]) -> int:
    if unicodedata.unidata_version != UNICODE:
        print(f"this Python has Unicode {unicodedata.unidata_version}, the table is pinned to {UNICODE}: use a Python that has {UNICODE} (3.12), "
              f"or change UNICODE here on purpose", file=sys.stderr)
        return 2
    if argv == ["--check"]:
        wrong = differing()
        print("\n".join(f"{name} differs from what Unicode {UNICODE} gives" for name in wrong) or f"both files are what Unicode {UNICODE} gives")
        return 1 if wrong else 0
    if argv:
        print(__doc__, file=sys.stderr)
        return 2
    table = ranges()
    PYTHON_FILE.write_text(python_text(table), encoding="utf-8")
    RUST_FILE.parent.mkdir(parents=True, exist_ok=True)
    RUST_FILE.write_text(rust_text(table), encoding="utf-8")
    print(f"{len(table)} ranges, {sum(high - low + 1 for low, high in table)} code points of Unicode {UNICODE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
