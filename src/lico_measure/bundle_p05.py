"""The M01-P05 inspection bundle: the product as one executable, restart recovery, the first view at two display scales."""

from __future__ import annotations

import html
import json
import time
from pathlib import Path

from .bundle import CRITERIA, LABELS, _cell, _find
from .bundle_p04 import _pre, _table


def _targets(raw: dict) -> str:
    rows = []
    for spec, metric, label in CRITERIA:
        record = _find(raw, "a2", metric)
        if not record:
            continue
        target = record.get("target")
        limit = f"{target['comparison']} {target['limit']}" if target else "no target"
        rows.append(f"<tr><td>{spec}</td><td>{html.escape(label)}</td><td>{limit}</td>{_cell(record)}</tr>")
    return f"<table><tr><th>ID</th><th>Measurement</th><th>Target</th><th>{html.escape(LABELS['a2'])}</th></tr>{''.join(rows)}</table>"


def render(raws: dict, p02: dict, p05: dict, tests: str, receipts: dict, bundle_commit: str) -> str:
    commits = ", ".join(f"{name} <code>{html.escape(r['commit'])}</code>" for name, r in receipts.items())
    gui = "".join(f"<h3>{html.escape(name)}</h3>{_targets(raw)}" for name, raw in raws.items())
    return f"""<!doctype html><meta charset='utf-8'><title>M01-P05 inspection</title>
<style>body{{font:14px sans-serif;max-width:1300px;margin:2em auto}}table{{border-collapse:collapse;width:100%}}
td,th{{border:1px solid #bbb;padding:3px 6px;vertical-align:top;font-size:12px}}.met{{background:#e6f4ea}}.missed{{background:#fce8e6}}
.unverified{{background:#fff4d6}}pre{{background:#f4f4f4;padding:8px;overflow:auto;font-size:12px}}</style>
<h1>M01-P05 workflow, recovery and the single executable - inspection bundle</h1>
<p>Verdict: <b>pending</b>. Runs: {commits}; bundle <code>{html.escape(bundle_commit)}</code>. Provider results are from protocol
<b>simulators</b> (test doubles); keyrings are throwaway private ones with canary values; no real account, login or provider turn was used by the
development session. Xvfb (X11, no compositor, software rendering); Wayland, GPU, other input methods and accessibility are unverified.</p>
<h2>The product is one file</h2>{_pre(p05['inventory'])}
<h2>Restart recovery at scale (simulator provider, host killed without warning)</h2>{_pre(p05['recovery'])}
<h2>Host memory during a sign-in (test double)</h2>{_pre(p05.get('login_memory', 'not measured'))}\n<h2>GUI targets with agent-shaped UTF-8 output (10000-line transcripts, 10 accounts on the host)</h2>{gui}
<h2>Host memory with agent-shaped transcripts</h2>
<table><tr><th>Metric</th><th>Workload</th><th>Scope</th><th>Value</th><th>Samples</th></tr>{_table(p02['host_resources']['measurements'])}</table>
<h2>Test suite, run on the same commit</h2><pre>{html.escape(tests)}</pre>
"""


README = """# M01-P05 workflow, recovery and the single executable - inspection bundle

Verdict: pending

Generated by `python -m lico_measure p05-bundle`; `receipt.json` lists the command, commits, binary hashes and workloads.
Open `index.html`. The owner's own end-to-end steps are in `doc/manual_end_to_end.md` of the repository.

## What to look at

- One file, `lico`: size, hash, the only libraries it links, what it does alone in an empty directory.
- Restart recovery: a host killed without warning, restarted, every session back as disconnected with its history and sequence.
- The first view at display scale 1 and 2, and the host's memory with long transcripts.

## Looks right when

- Nothing runs, is shown as connected or is billed without the person's action after a restart.
- Misses and unverified items are marked as such, and no value is shown as zero when it was not measured.
"""


def build(raws: dict, p02: dict, p05: dict, tests: str, out: Path, command: str, commit: str, receipts: dict) -> None:
    out.mkdir(parents=True, exist_ok=True)
    (out / "index.html").write_text(render(raws, p02, p05, tests, receipts, commit))
    (out / "report.json").write_text(json.dumps({"p02_text": p02, "p05": p05, "gui_experiments": {k: v["candidates"] for k, v in raws.items()}, "tests": tests}, indent=1, ensure_ascii=False))
    (out / "README.md").write_text(README)
    (out / "receipt.json").write_text(json.dumps({"bundle_command": command, "bundle_commit": commit, "measurement_receipts": receipts,
                                                  "generated": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "verdict": "pending"}, indent=1))
