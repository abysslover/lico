"""The M01-P02 inspection bundle: what an owner sees of the persistent host."""

from __future__ import annotations

import html
import json
import time
from pathlib import Path

from . import p02
from .bundle import CRITERIA, LABELS, _cell, _find
from .hostile import run_hostd_suite


def _pre(value) -> str:
    return "<pre>" + html.escape(json.dumps(value, indent=1, ensure_ascii=False)) + "</pre>"


def collect_p02(out: Path) -> dict:
    """Run every P02 scenario and experiment once and return the raw results."""
    results: dict = {}
    results["host_resources"] = p02.host_resources()
    results["backpressure"] = p02.backpressure()
    results["input_integrity"] = p02.input_integrity()
    results["cli"] = p02.cli_transcript()
    results["input_states"] = p02.input_states_demo()
    results["hostile"] = run_hostd_suite()
    results["gui_kill"] = {name: p02.gui_kill(name) for name in ("a2", "c2")}
    results["view_switch"] = {name: p02.view_switch(name) for name in ("a2", "c2")}
    results["shots"] = {name: p02.gui_kill_shots(name, out / "screens") for name in ("a2", "c2")}
    return results


def render(raw: dict, results: dict, receipt: dict) -> str:
    names = [c for c in ("a2", "c2") if c in raw["candidates"]]
    head = "".join(f"<th>{html.escape(LABELS[c])}</th>" for c in names)
    rows = []
    for spec, metric, label in CRITERIA:
        records = [_find(raw, c, metric) for c in names]
        if not any(records):
            continue
        target = next((r["target"] for r in records if r and "target" in r), None)
        limit = f"{target['comparison']} {target['limit']}" if target else "no target"
        rows.append(f"<tr><td>{spec}</td><td>{html.escape(label)}</td><td>{limit}</td>{''.join(_cell(r) for r in records)}</tr>")
    host_rows = []
    for m in results["host_resources"]["measurements"]:
        host_rows.append(f"<tr><td>{html.escape(m['metric'])}</td><td>{html.escape(m['scope']['workload'])}</td>"
                         f"<td>{m['value']:.1f} {html.escape(m['unit'])}</td><td>n={m['n']}</td></tr>")
    hostile = "".join(f"<tr><td>{html.escape(h['case'])}</td><td>{h['rejected']}</td><td>{h['no_effect']}</td><td>{html.escape(h['detail'])}</td></tr>"
                      for h in results["hostile"])
    shots = []
    for name, named in results["shots"].items():
        shots.append(f"<h3>GUI {html.escape(LABELS[name])}: killed and replaced</h3><div class='shots'>")
        for label, file in named.items():
            shots.append(f"<figure><img src='screens/{html.escape(file)}' width='380'><figcaption>{html.escape(label)}</figcaption></figure>")
        shots.append("</div>")
    cli = "".join(f"<h4><code>{html.escape(s['command'])}</code> (exit {s['exit']})</h4><pre>{html.escape(s['stdout'] or s['stderr'])}</pre>"
                  for s in results["cli"]["steps"])
    return f"""<!doctype html><meta charset='utf-8'><title>M01-P02 inspection</title>
<style>body{{font:14px sans-serif;max-width:1300px;margin:2em auto}}table{{border-collapse:collapse;width:100%}}
td,th{{border:1px solid #bbb;padding:3px 6px;vertical-align:top;font-size:12px}}.met{{background:#e6f4ea}}.missed{{background:#fce8e6}}
.unverified{{background:#fff4d6}}.shots{{display:flex;gap:8px;flex-wrap:wrap}}pre{{background:#f4f4f4;padding:8px;overflow:auto;font-size:12px}}</style>
<h1>M01-P02 persistent host - inspection bundle</h1>
<p>Verdict: <b>pending</b>. Targets are copied from the product specification. Commit: <code>{html.escape(receipt['commit'])}</code>.
Xvfb (X11, no compositor, software rendering); Wayland, a real compositor, GPU, other input methods and accessibility are unverified.</p>
<h2>GUI targets with the owned host (primary A2, fallback C2)</h2>
<table><tr><th>ID</th><th>Measurement</th><th>Target</th>{head}</tr>{''.join(rows)}</table>
<h2>Host memory (the owned host)</h2>
<table><tr><th>Metric</th><th>Workload</th><th>Value</th><th>Samples</th></tr>{''.join(host_rows)}</table>
<h2>GUI killed while the host works (counters)</h2>{_pre(results['gui_kill'])}{''.join(shots)}
<h2>View switched mid-composition (Korean, real input method)</h2>{_pre(results['view_switch'])}
<h2>Backpressure: one stalled subscriber</h2>{_pre(results['backpressure']['observations'])}
<h2>Input integrity</h2>{_pre(results['input_integrity']['observations'])}
<h2>Input states and an approval on the wire</h2>{_pre(results['input_states'])}
<h2>Command line transcripts</h2>{cli}
<h2>Rejected hostile requests (attacker's view)</h2>
<table><tr><th>Case</th><th>Rejected</th><th>No effect</th><th>Detail</th></tr>{hostile}</table>
"""


README = """# M01-P02 persistent host - inspection bundle

Verdict: pending

Generated by `python -m lico_measure p02-bundle`; `receipt.json` lists the command,
the exact commit, the binary hashes and the workload. Open `index.html`.

## What to look at

- The GUI targets measured with the owned host, for the primary and the fallback client.
- A GUI killed while the host works: counters and three screens (attached, killed,
  replaced). The agent process, the output and the log stay unbroken.
- A view switched in the middle of a Korean composition: what each session received.
- One stalled subscriber, input integrity with lost replies, an input's three states
  and an approval on the wire, and every command line transcript.
- The rejected hostile requests as an attacker would see them.

## Looks right when

- The correct session stays identifiable, hidden work continues, a restarted GUI shows
  current content, and no input lands in a stale target.
- Nothing typed in one session appears in another.
- No value is shown as zero when it was not measured.
- A screenshot alone does not prove input, continuity or latency; the counters do.
"""


def build(raw_dirs: list[Path], results: dict, out: Path, command: str, commit: str, receipts: list[dict]) -> None:
    raw: dict = {"candidates": {}}
    for raw_dir in raw_dirs:
        for candidate, experiments in json.loads((raw_dir / "raw.json").read_text())["candidates"].items():
            raw["candidates"].setdefault(candidate, {}).update(experiments)
    out.mkdir(parents=True, exist_ok=True)
    (out / "index.html").write_text(render(raw, results, receipts[-1]))
    (out / "report.json").write_text(json.dumps({"p02": results, "gui_experiments": raw["candidates"]}, indent=1, ensure_ascii=False))
    (out / "README.md").write_text(README)
    (out / "receipt.json").write_text(json.dumps({
        "bundle_command": command, "bundle_commit": commit, "measurement_receipts": receipts,
        "generated": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "verdict": "pending"}, indent=1))
